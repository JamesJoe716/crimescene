  function renderTable() {
    var view = VIEWS[current];
    document.getElementById("tabhint").textContent = view.hint;

    var rows = view.rows().slice();
    var needle = query.value.trim().toLowerCase();
    if (needle) {
      rows = rows.filter(function (row) {
        var hay = (row.path || "") + " " + (row.a || "") + " " + (row.b || "") + " " +
                  (row.author || "") + " " + (row.mainAuthor || "");
        return hay.toLowerCase().indexOf(needle) !== -1;
      });
    }
    if (sortKey) {
      rows.sort(function (x, y) {
        var a = x[sortKey], b = y[sortKey];
        if (typeof a === "number" && typeof b === "number") return sortAsc ? a - b : b - a;
        a = String(a); b = String(b);
        return sortAsc ? a.localeCompare(b) : b.localeCompare(a);
      });
    }

    var head = table.tHead, body = table.tBodies[0];
    head.textContent = ""; body.textContent = "";
    var tr = el("tr");
    view.columns.forEach(function (col) {
      var th = el("th", null, col.label);
      if (col.num) th.className = "num";
      if (col.k === sortKey) th.className = (th.className + " sorted " + (sortAsc ? "asc" : "")).trim();
      th.addEventListener("click", function () {
        if (sortKey === col.k) sortAsc = !sortAsc;
        else { sortKey = col.k; sortAsc = false; }
        renderTable();
      });
      tr.appendChild(th);
    });
    head.appendChild(tr);

    rows.slice(0, 300).forEach(function (row) {
      var line = el("tr");
      view.columns.forEach(function (col) {
        var cell = el("td");
        if (col.num) cell.className = "num";
        if (col.path) cell.className = "path";
        var value = col.render ? col.render(row) : row[col.k];
        if (value && value.nodeType) cell.appendChild(value);
        else cell.textContent = typeof value === "number" ? num(value) : String(value == null ? "—" : value);
        line.appendChild(cell);
      });
      body.appendChild(line);
    });

    emptyNote.hidden = rows.length > 0;
  }

