import { RAMP_DARK, RAMP_LIGHT, SHARED_SOURCE } from "./treemap.js";
import type { XrayReport } from "./types.js";

/**
 * Renders the analysis as a single self-contained HTML file: no CDN, no fonts,
 * no fetch. It has to open from `file://` on a locked-down laptop, so every
 * byte it needs is inlined here.
 *
 * Colour follows a sequential encoding — one hue, monotone lightness — stepped
 * separately for each surface rather than flipped. On the dark surface the ramp
 * runs the other way so "near zero" always recedes toward the background.
 *
 * The layout maths is not duplicated here: `SHARED_SOURCE` is the literal
 * source of the functions in `treemap.ts`, so the browser and the `--svg`
 * renderer run the same code rather than two copies that drift.
 */

export function renderReport(report: XrayReport): string {
  // The payload sits in an `application/json` block read via textContent, so the
  // only sequence that could break out of it is `</script>`. Escaping `<` is
  // enough, and JSON.parse decodes the escape on the way back in.
  const payload = JSON.stringify(report).replace(/</g, "\\u003c");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="crimescene ${escapeHtml(report.tool.version)}">
<title>${escapeHtml(report.repo)} — crimescene report</title>
<style>${STYLE}</style>
</head>
<body>
<div class="wrap">
  <header class="head">
    <div>
      <h1>${escapeHtml(report.repo)}</h1>
      <p class="sub" id="sub"></p>
    </div>
    <button id="theme" class="ghost" type="button" aria-label="Toggle colour theme">Theme</button>
  </header>

  <section class="tiles" id="tiles" aria-label="Summary"></section>

  <section class="panel">
    <div class="panel-head">
      <div>
        <h2>Hotspot map</h2>
        <p class="hint">Area = lines of code &nbsp;·&nbsp; colour = hotspot score &nbsp;·&nbsp; click a folder to zoom in</p>
      </div>
      <nav class="crumbs" id="crumbs" aria-label="Breadcrumb"></nav>
    </div>
    <div class="mapwrap">
      <svg id="map" viewBox="0 0 1000 580" preserveAspectRatio="xMidYMid meet" role="img"
           aria-label="Treemap of the repository, sized by lines of code and coloured by hotspot score"></svg>
      <div id="tip" class="tip" role="tooltip" aria-hidden="true"></div>
    </div>
    <div class="legend" aria-hidden="true">
      <span class="legend-label">cold</span>
      <span class="legend-bar" id="legendbar"></span>
      <span class="legend-label">hot</span>
    </div>
  </section>

  <section class="panel">
    <div class="tabs" role="tablist">
      <button class="tab is-on" role="tab" data-tab="hotspots" type="button">Hotspots</button>
      <button class="tab" role="tab" data-tab="knowledge" type="button">Knowledge risk</button>
      <button class="tab" role="tab" data-tab="coupling" type="button">Coupling</button>
      <button class="tab" role="tab" data-tab="authors" type="button">Authors</button>
      <input id="q" class="search" type="search" placeholder="Filter by path or name…" aria-label="Filter rows">
    </div>
    <p class="hint" id="tabhint"></p>
    <div class="tablewrap"><table id="table"><thead></thead><tbody></tbody></table></div>
    <p class="empty" id="empty" hidden>Nothing matches that filter.</p>
  </section>

  <section class="panel notes" id="notes"></section>

  <footer class="foot">
    Generated by <strong>crimescene</strong> v${escapeHtml(report.tool.version)} ·
    <span id="stamp"></span> · analysis runs entirely offline
  </footer>
</div>
<script id="data" type="application/json">${payload}</script>
<script>${SCRIPT.replace("__RAMP_LIGHT__", JSON.stringify(RAMP_LIGHT))
    .replace("__RAMP_DARK__", JSON.stringify(RAMP_DARK))
    .replace("__SHARED__", () => SHARED_SOURCE)}</script>
</body>
</html>
`;
}

function escapeHtml(text: string): string {
  return text.replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[char] ?? char,
  );
}

